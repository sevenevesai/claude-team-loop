"""Condense Claude Code session transcripts into per-project digests (read-only on the input).

Usage: python -I extract.py --out DIR [--projects-dir DIR] [--match SUBSTRING ...] [--since YYYY-MM-DD]

Writes digest-<project>.jsonl/.md, summary.md and run-stats.json into --out.
Privacy: digests contain whatever the prompts contained (customer or project data, credentials,
personal details). Keep the output on this machine.
"""
import json, os, re, sys, hashlib, collections, argparse, datetime
from concurrent.futures import ProcessPoolExecutor

UUID_FILE = re.compile(r'^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}\.jsonl$')
FIRST_MAX, LATER_MAX, MAX_PROMPTS, HEAD, TAIL, TOPN = 1500, 400, 12, 8, 4, 15
MD_PART_LIMIT = 300 * 1024

# non-conversation records, skipped without parsing (they are large or irrelevant)
SKIP_PREFIXES = tuple('{"type":"%s' % t for t in (
    'api-request', 'file-history', 'atis-latch', 'last-prompt', 'permission-mode', 'mode', 'cost-state',
    'tools-used', 'queue-operation', 'progress'))

STRIP_TAGS = ['system-reminder', 'local-command-caveat', 'local-command-stderr', 'ide_opened_file', 'ide_selection',
              'ide_diagnostics', 'user-prompt-submit-hook', 'command-message', 'bash-stdout', 'bash-stderr',
              'system_instruction', 'task-notification']
STRIP_RE = [re.compile(r'<%s(?:\s[^>]*)?>.*?</%s>' % (t, t), re.S) for t in STRIP_TAGS]
PASTED_TAG_RE = re.compile(r'</?pasted_content(?:\s[^>]*)?>')
IMAGE_NOTE_RE = re.compile(r'\[Image: [^\]]*\]')
CMD_NAME_RE = re.compile(r'<command-name>\s*(.*?)\s*</command-name>', re.S)
CMD_ARGS_RE = re.compile(r'<command-args>(.*?)</command-args>', re.S)
BASH_INPUT_RE = re.compile(r'<bash-input>(.*?)</bash-input>', re.S)
BLANKS_RE = re.compile(r'\n{3,}')

SHELL_TOOLS = ('Bash', 'PowerShell')
WRITE_TOOLS = {'Write': 'file_path', 'Edit': 'file_path', 'MultiEdit': 'file_path', 'NotebookEdit': 'notebook_path'}
AGENT_TOOLS = ('Agent', 'Task')

SKIP_CMDS = {'cd', 'set-location', 'sl', 'pushd', 'popd', 'export'}
LEAD_KEYWORDS = {'do', 'then', 'else', '!', 'time', 'if', 'elif', 'while', 'until', 'try', 'catch', 'finally', '{', '&', '(', '&&'}
SKIP_SEGMENTS = {'done', 'fi', 'esac', '}', ')', 'for', 'foreach', '[', '[[', ']', ']]', 'function', 'return', 'switch',
                 'case', 'break', 'continue', 'param', 'set', 'unset'}
SUBCMD_TOOLS = {'git', 'npm', 'npx', 'pnpm', 'yarn', 'cargo', 'gh', 'docker', 'pip', 'pip3', 'uv', 'dotnet', 'go',
                'kubectl', 'winget', 'choco', 'scoop', 'gcloud', 'az', 'make', 'rustup', 'tauri'}
OPT_VALUE = {'git': {'-C', '-c', '--git-dir', '--work-tree'}, 'npm': {'--prefix', '-C'}, 'pnpm': {'--prefix', '-C'},
             'yarn': {'--cwd'}, 'cargo': {'--manifest-path', '-p'}, 'gh': {'-R', '--repo'}}
WORD_RE = re.compile(r'^[a-z][a-z0-9:_-]*$')
TOKEN_RE = re.compile(r'"[^"]*"|\'[^\']*\'|\S+')
HEREDOC_RE = re.compile(r'<<-?\s*[\'"]?([A-Za-z_][A-Za-z0-9_]*)[\'"]?')


def strip_text(s):
    for r in STRIP_RE:
        s = r.sub('', s)
    s = PASTED_TAG_RE.sub('', s)
    s = IMAGE_NOTE_RE.sub('', s)
    s = re.sub(r'[ \t]{3,}', ' ', s)
    return BLANKS_RE.sub('\n\n', s).strip()


def trunc(s, n):
    return s if len(s) <= n else s[:n] + '...[+%d chars]' % (len(s) - n)


def classify_text(text, origin, prompt_source):
    """Return (kind, prompt_text_or_None). kind 'prompt' means a human-authored prompt."""
    if isinstance(origin, dict) and origin.get('kind') not in (None, 'human'):
        return 'non_human_origin', None
    if prompt_source == 'system':
        return 'system_source', None
    head = text.lstrip()[:200]
    if head.startswith(('<task-notification', '<agent-notification', '<agent-message', '<bash-notification')):
        return 'notification', None
    if head.startswith('[orchestration]'):
        return 'orchestration_signal', None
    if head.startswith('[Request interrupted'):
        return 'interrupt', None
    if head.startswith('This session is being continued from a previous conversation'):
        return 'compact_continuation', None
    if head.startswith(('<local-command-stdout', '<bash-stdout', '<local-command-stderr')):
        return 'local_command_output', None
    cm = CMD_NAME_RE.search(text)
    if cm:
        name = cm.group(1).strip()
        if not name.startswith('/'):
            name = '/' + name
        am = CMD_ARGS_RE.search(text)
        args = am.group(1).strip() if am else ''
        return 'slash', (name + (' ' + args if args else '')).strip()
    bm = BASH_INPUT_RE.search(text)
    if bm:
        return 'prompt', '!' + bm.group(1).strip()
    t = strip_text(text)
    if t.startswith('Caveat: The messages below were generated by the user while running local commands'):
        return 'local_command_output', None
    if not t:
        return 'empty_after_strip', None
    return 'prompt', t


def split_segments(cmd):
    """Split a shell command into top-level segments, dropping heredoc / here-string bodies."""
    kept, skip_tag, skip_ps = [], None, False
    for ln in cmd.split('\n'):
        if skip_tag is not None:
            if ln.strip() == skip_tag:
                skip_tag = None
            continue
        if skip_ps:
            if ln.startswith(("'@", '"@')):
                skip_ps = False
            continue
        m = HEREDOC_RE.search(ln)
        if m:
            kept.append(ln[:m.start()])
            skip_tag = m.group(1)
            continue
        s = ln.rstrip()
        if s.endswith(("@'", '@"')):
            kept.append(s[:-2])
            skip_ps = True
            continue
        kept.append(ln)
    text = '\n'.join(kept)
    text = re.sub(r'[\\`][ \t]*\r?\n', ' ', text)
    segs, cur, q, i, n = [], [], None, 0, len(text)
    while i < n:
        c = text[i]
        if q:
            cur.append(c)
            if c == q:
                q = None
            i += 1
            continue
        if c in '"\'':
            q = c
            cur.append(c)
            i += 1
            continue
        two = text[i:i + 2]
        if two in ('&&', '||'):
            segs.append(''.join(cur)); cur = []; i += 2
            continue
        if c in ';\n':
            segs.append(''.join(cur)); cur = []; i += 1
            continue
        cur.append(c)
        i += 1
    segs.append(''.join(cur))
    return [s.strip() for s in segs if s.strip()]


def unquote(t):
    return t[1:-1] if len(t) >= 2 and t[0] in '"\'' and t[-1] == t[0] else t


def segment_label(seg):
    toks = [unquote(t) for t in TOKEN_RE.findall(seg)]
    while toks and (toks[0] == '&' or re.match(r'^[A-Za-z_][A-Za-z0-9_]*=', toks[0]) or toks[0].lower() in LEAD_KEYWORDS):
        toks.pop(0)
    if not toks:
        return None
    first = toks[0].lstrip('({')
    if not first:
        return None
    if first.startswith('$'):
        return None
    if first.startswith('-') or first.lower() in SKIP_SEGMENTS:
        return None
    base = first.split(')')[0].replace('\\', '/').rsplit('/', 1)[-1].lower()
    for suffix in ('.exe', '.cmd', '.bat'):
        if base.endswith(suffix):
            base = base[:-len(suffix)]
    if not base or base in SKIP_CMDS:
        return None
    rest = toks[1:]
    if base in ('sf', 'sfdx'):
        out = [base]
        for t in rest:
            if len(out) >= 4 or not WORD_RE.match(t):
                break
            out.append(t)
        return ' '.join(out)
    if base in SUBCMD_TOOLS:
        vopts = OPT_VALUE.get(base, set())
        i = 0
        while i < len(rest) and rest[i].startswith('-'):
            i += 2 if rest[i] in vopts else 1
        if i < len(rest) and WORD_RE.match(rest[i]):
            return base + ' ' + rest[i]
    return base


def path_group(path, cwd):
    p = path.replace('\\', '/').strip()
    low = p.lower()
    c = (cwd or '').replace('\\', '/').rstrip('/')
    if c and low.startswith(c.lower() + '/'):
        rest = p[len(c) + 1:]
        return rest.split('/')[0] if '/' in rest else '(cwd root)'
    absolute = bool(re.match(r'^[A-Za-z]:/', p)) or p.startswith(('/', '~'))
    if not absolute:
        if p.startswith('./'):
            p = p[2:]
        return p.split('/')[0] if '/' in p else '(cwd root)'
    if '/scratchpad/' in low:
        return '(scratchpad)'
    return '(outside cwd)'


def file_ext(path):
    name = path.replace('\\', '/').rsplit('/', 1)[-1]
    ext = os.path.splitext(name)[1].lower()
    if not ext:
        return name.lower() if name.startswith('.') else '(none)'
    return ext


def text_of_content(c):
    """Text of a user message; None when it is a tool_result carrier."""
    if isinstance(c, str):
        return c
    if isinstance(c, list):
        if any(isinstance(b, dict) and b.get('type') == 'tool_result' for b in c):
            return None
        parts = [b.get('text', '') for b in c if isinstance(b, dict) and b.get('type') == 'text']
        return '\n'.join(parts)
    return None


def process_main(args):
    path, project = args
    sid = os.path.basename(path)[:-6]
    cnt = {k: collections.Counter() for k in ('slash', 'skills', 'subagent_types', 'mcp', 'shell', 'write_ext', 'write_dir')}
    excluded = collections.Counter()
    first_prompts, tail_prompts = [], collections.deque(maxlen=TAIL)
    recent_texts = collections.deque(maxlen=6)
    prompt_count = lines = bad = sidechain_lines = 0
    first_ts = last_ts = cwd = branch = ai_title = None
    cwds, branches, sids = set(), [], set()
    turns, seen_tool_ids = set(), set()
    entrypoints = set()

    def add_prompt(text, src):
        nonlocal prompt_count
        prompt_count += 1
        rec = {'i': prompt_count, 'chars': len(text), 'text': trunc(text, FIRST_MAX if prompt_count == 1 else LATER_MAX)}
        if src:
            rec['src'] = src
        if len(first_prompts) < HEAD:
            first_prompts.append(rec)
        else:
            tail_prompts.append(rec)
        recent_texts.append(text)

    with open(path, encoding='utf-8', errors='replace') as fh:
        for ln in fh:
            lines += 1
            if ln.startswith(SKIP_PREFIXES):
                continue
            try:
                o = json.loads(ln)
            except Exception:
                bad += 1
                continue
            if not isinstance(o, dict):
                bad += 1
                continue
            t = o.get('type')
            if t == 'ai-title':
                ai_title = o.get('aiTitle') or ai_title
                continue
            if o.get('sessionId'):
                sids.add(o['sessionId'])
            ts = o.get('timestamp')
            if isinstance(ts, str):
                if first_ts is None or ts < first_ts:
                    first_ts = ts
                if last_ts is None or ts > last_ts:
                    last_ts = ts
            if o.get('cwd'):
                if cwd is None:
                    cwd = o['cwd']
                cwds.add(o['cwd'])
            gb = o.get('gitBranch')
            if gb and gb not in branches:
                branches.append(gb)
            if o.get('entrypoint'):
                entrypoints.add(o['entrypoint'])
            if o.get('isSidechain'):
                sidechain_lines += 1
                continue
            msg = o.get('message')
            if t == 'user' and isinstance(msg, dict):
                if o.get('isMeta'):
                    excluded['meta'] += 1
                    continue
                if o.get('isCompactSummary'):
                    excluded['compact_continuation'] += 1
                    continue
                text = text_of_content(msg.get('content'))
                if text is None:
                    continue
                kind, ptxt = classify_text(text, o.get('origin'), o.get('promptSource'))
                if kind == 'slash':
                    cnt['slash'][ptxt.split(' ', 1)[0]] += 1
                    kind = 'prompt'
                if kind != 'prompt':
                    excluded[kind] += 1
                    continue
                src = o.get('promptSource')
                add_prompt(ptxt, None if src in (None, 'typed') else src)
            elif t == 'attachment':
                a = o.get('attachment')
                if isinstance(a, dict) and a.get('type') == 'queued_command':
                    if a.get('isMeta'):
                        excluded['meta'] += 1
                        continue
                    pr = a.get('prompt')
                    text = pr if isinstance(pr, str) else text_of_content(pr)
                    if text is None:
                        continue
                    kind, ptxt = classify_text(text, a.get('origin'), None)
                    if kind == 'slash':
                        cnt['slash'][ptxt.split(' ', 1)[0]] += 1
                        kind = 'prompt'
                    if kind != 'prompt':
                        excluded[kind] += 1
                        continue
                    if ptxt in recent_texts:
                        excluded['queued_duplicate'] += 1
                        continue
                    add_prompt(ptxt, 'queued')
            elif t == 'assistant' and isinstance(msg, dict):
                turns.add(msg.get('id') or o.get('requestId') or o.get('uuid'))
                content = msg.get('content')
                if not isinstance(content, list):
                    continue
                for b in content:
                    if not isinstance(b, dict) or b.get('type') != 'tool_use':
                        continue
                    bid = b.get('id')
                    if bid in seen_tool_ids:
                        continue
                    seen_tool_ids.add(bid)
                    name, inp = b.get('name') or '', b.get('input')
                    if not isinstance(inp, dict):
                        inp = {}
                    if name == 'Skill':
                        cnt['skills'][str(inp.get('skill', '(none)'))] += 1
                    elif name in AGENT_TOOLS:
                        cnt['subagent_types'][str(inp.get('subagent_type') or '(none)')] += 1
                    elif name.startswith('mcp__'):
                        cnt['mcp'][name] += 1
                    elif name in SHELL_TOOLS:
                        cmd = inp.get('command')
                        if isinstance(cmd, str):
                            for seg in split_segments(cmd):
                                lab = segment_label(seg)
                                if lab:
                                    cnt['shell'][lab] += 1
                    elif name in WRITE_TOOLS:
                        fp = inp.get(WRITE_TOOLS[name])
                        if isinstance(fp, str) and fp:
                            cnt['write_ext'][file_ext(fp)] += 1
                            cnt['write_dir'][path_group(fp, o.get('cwd') or cwd)] += 1

    prompts = first_prompts + list(tail_prompts)
    return {
        'project': project, 'session_id': sid, 'file_bytes': os.path.getsize(path),
        'cwd': cwd, 'cwd_distinct': len(cwds), 'git_branch': branches[0] if branches else None,
        'git_branches_distinct': len(branches), 'entrypoints': sorted(entrypoints),
        'first_ts': first_ts, 'last_ts': last_ts, 'lines': lines, 'bad_lines': bad,
        'sidechain_lines_in_main': sidechain_lines, 'session_ids_in_file': len(sids),
        'assistant_turns': len(turns), 'ai_title': ai_title,
        'prompt_count': prompt_count, 'prompts_shown': len(prompts), 'prompts': prompts,
        'excluded': dict(excluded), 'subagent_files': 0,
        'full': {k: dict(v) for k, v in cnt.items()},
    }


def peek_session_id(path):
    rx = re.compile(r'"sessionId":"([0-9a-f-]{36})"')
    with open(path, encoding='utf-8', errors='replace') as fh:
        for i, ln in enumerate(fh):
            m = rx.search(ln[:3000])
            if m:
                return m.group(1)
            if i > 60:
                break
    return None


def process_agent(path):
    return path, peek_session_id(path)


def top(d, n=TOPN):
    return dict(sorted(d.items(), key=lambda kv: (-kv[1], kv[0]))[:n])


def short_project_name(name):
    if len(name) <= 70:
        return name
    return name[:30] + '__' + hashlib.sha1(name.encode()).hexdigest()[:6] + '__' + name[-25:]


def md_session(r):
    date = (r['first_ts'] or '????-??-??')[:10]
    hdr = '## %s | %s | %s | turns %d | prompts %d | subagent-files %d | cwd %s' % (
        date, r['session_id'][:8], r['git_branch'] or '-', r['assistant_turns'], r['prompt_count'],
        r['subagent_files'], r['cwd'] or '-')
    out = [hdr]
    if r['ai_title']:
        out.append('title: ' + r['ai_title'])
    for p in r['prompts']:
        txt = p['text'].replace('\r', '').replace('\n', ' \u23ce ')
        out.append('- [%d%s] %s' % (p['i'], ' ' + p['src'] if p.get('src') else '', txt))
    if r['prompt_count'] > r['prompts_shown']:
        out.append('- (%d prompts omitted between 8th and last 4)' % (r['prompt_count'] - r['prompts_shown']))
    parts = []
    for label, key in (('slash', 'slash'), ('skills', 'skills'), ('agents', 'subagent_types'), ('mcp', 'mcp'),
                       ('shell', 'shell'), ('write-ext', 'write_ext'), ('write-dir', 'write_dir')):
        d = r['top'][key]
        if d:
            parts.append('%s: %s' % (label, ', '.join('%s x%d' % kv for kv in d.items())))
    out.append('counts> ' + (' | '.join(parts) if parts else '(none)'))
    return '\n'.join(out) + '\n\n'


def write_md(out, project_short, sessions):
    parts, cur, size = [], [], 0
    for r in sessions:
        block = md_session(r)
        b = len(block.encode('utf-8'))
        if cur and size + b > MD_PART_LIMIT:
            parts.append(cur); cur, size = [], 0
        cur.append(block); size += b
    if cur or not parts:
        parts.append(cur)
    names = []
    for i, blocks in enumerate(parts, 1):
        fn = 'digest-%s.md' % project_short if len(parts) == 1 else 'digest-%s-part%d.md' % (project_short, i)
        with open(os.path.join(out, fn), 'w', encoding='utf-8', newline='\n') as f:
            f.write('# %s%s\n\n' % (project_short, '' if len(parts) == 1 else ' (part %d of %d)' % (i, len(parts))))
            f.write(''.join(blocks))
        names.append(fn)
    return names


def default_projects_dir():
    cfg = os.environ.get('CLAUDE_CONFIG_DIR')
    base = cfg if cfg else os.path.join(os.path.expanduser('~'), '.claude')
    return os.path.join(base, 'projects')


def is_inside(child, parent):
    child, parent = os.path.normcase(os.path.realpath(child)), os.path.normcase(os.path.realpath(parent))
    try:
        return os.path.commonpath([child, parent]) == parent
    except ValueError:  # different drives
        return False


def main():
    ap = argparse.ArgumentParser(
        prog='extract.py', description='Condense Claude Code session transcripts into per-project digests.',
        epilog='Digests contain whatever the prompts contained; keep them on this machine.')
    ap.add_argument('--out', required=True, help='output directory (created if missing; must not be inside the projects dir)')
    ap.add_argument('--projects-dir', default=None,
                    help='transcripts root (default: %%CLAUDE_CONFIG_DIR%%/projects if set, else ~/.claude/projects)')
    ap.add_argument('--match', action='append', default=[], metavar='SUBSTRING',
                    help='keep only project folders whose name contains SUBSTRING (case-insensitive; repeatable)')
    ap.add_argument('--since', default=None, metavar='YYYY-MM-DD',
                    help='skip sessions whose last timestamp is earlier than this date')
    a = ap.parse_args()

    root = os.path.abspath(a.projects_dir if a.projects_dir else default_projects_dir())
    if not os.path.isdir(root):
        ap.error('projects directory not found: %s' % root)
    out = os.path.abspath(a.out)
    if is_inside(out, root):
        ap.error('--out must not be inside the projects directory (%s)' % root)
    if os.path.exists(out) and not os.path.isdir(out):
        ap.error('--out exists and is not a directory: %s' % out)
    since = None
    if a.since is not None:
        try:
            since = datetime.date.fromisoformat(a.since).isoformat()
        except ValueError:
            ap.error('--since must be a date in YYYY-MM-DD format, got %r' % a.since)
    needles = [m.lower() for m in a.match]
    if any(not m for m in needles):
        ap.error('--match must not be empty')

    projects = sorted(d for d in os.listdir(root) if os.path.isdir(os.path.join(root, d))
                      and (not needles or any(n in d.lower() for n in needles)))
    if needles and not projects:
        ap.error('no project folder in %s matches %s' % (root, ', '.join(repr(m) for m in a.match)))
    os.makedirs(out, exist_ok=True)
    workers = min(8, os.cpu_count() or 1)

    main_jobs, agent_jobs = [], []   # agent_jobs: (project, path, parent_sid_or_None)
    for proj in projects:
        base = os.path.join(root, proj)
        for dp, dn, fn in os.walk(base):
            rel = os.path.relpath(dp, base)
            for f in fn:
                if not f.endswith('.jsonl'):
                    continue
                fp = os.path.join(dp, f)
                if rel == '.' and UUID_FILE.match(f):
                    main_jobs.append((fp, proj))
                else:
                    parent = rel.split(os.sep)[0] if rel != '.' else None
                    agent_jobs.append((proj, fp, parent, f.startswith('agent-')))

    by_proj = collections.defaultdict(dict)
    dropped = set()   # (project, session_id) skipped by --since; their subagent files are not "unlinked"
    with ProcessPoolExecutor(max_workers=workers) as ex:
        root_agents = [j for j in agent_jobs if j[2] is None]
        peek = dict(ex.map(process_agent, [j[1] for j in root_agents], chunksize=16))
        for r in ex.map(process_main, main_jobs, chunksize=1):
            if since and r['last_ts'] and r['last_ts'][:10] < since:
                dropped.add((r['project'], r['session_id']))
                continue
            by_proj[r['project']][r['session_id']] = r

    proj_extra = collections.defaultdict(lambda: collections.Counter())
    for proj, fp, parent, is_agent in agent_jobs:
        if parent is None:
            parent = peek.get(fp)
        if (proj, parent) in dropped:
            continue
        sess = by_proj[proj].get(parent) if parent else None
        if not is_agent:
            proj_extra[proj]['non_agent_jsonl_in_subfolders'] += 1
        if sess is not None:
            sess['subagent_files'] += 1
        else:
            proj_extra[proj]['unlinked_subagent_files'] += 1

    if since:
        projects = [p for p in projects if by_proj[p]]

    summary_rows, sumtables, mapping = [], {}, {}
    for proj in projects:
        sess = sorted(by_proj[proj].values(), key=lambda r: (r['first_ts'] is None, r['first_ts'] or '', r['session_id']))
        short = short_project_name(proj)
        mapping[proj] = short
        agg = {k: collections.defaultdict(lambda: [0, 0]) for k in ('slash', 'skills', 'subagent_types', 'mcp', 'shell', 'write_ext')}
        excl = collections.Counter()
        with open(os.path.join(out, 'digest-%s.jsonl' % short), 'w', encoding='utf-8', newline='\n') as jf:
            for r in sess:
                full = r.pop('full')
                r['top'] = {k: top(v) for k, v in full.items()}
                for k in agg:
                    for name, n in full[k].items():
                        agg[k][name][0] += n
                        agg[k][name][1] += 1
                excl.update(r['excluded'])
                jf.write(json.dumps(r, ensure_ascii=False) + '\n')
        md_files = write_md(out, short, sess)
        firsts = [r['first_ts'] for r in sess if r['first_ts']]
        lasts = [r['last_ts'] for r in sess if r['last_ts']]
        summary_rows.append({
            'project': proj, 'sessions': len(sess),
            'first': min(firsts)[:10] if firsts else '-', 'last': max(lasts)[:10] if lasts else '-',
            'prompts': sum(r['prompt_count'] for r in sess),
            'zero': sum(1 for r in sess if r['prompt_count'] == 0),
            'subagent_files': sum(r['subagent_files'] for r in sess),
            'unlinked': proj_extra[proj]['unlinked_subagent_files'],
            'parts': len(md_files), 'bad_lines': sum(r['bad_lines'] for r in sess),
            'multi_sid': sum(1 for r in sess if r['session_ids_in_file'] > 1),
            'sidechain_in_main': sum(r['sidechain_lines_in_main'] for r in sess),
            'excluded': dict(excl),
        })
        sumtables[proj] = agg

    with open(os.path.join(out, 'summary.md'), 'w', encoding='utf-8', newline='\n') as f:
        f.write('# Digest summary\n\n')
        f.write('Counts are totals over main sessions (calls = occurrences, sess = sessions using it). Sidechain/subagent transcripts are counted only as files.\n\n')
        f.write('| project | sessions | first | last | prompts | zero-prompt sessions | subagent files (linked / unlinked) | md parts |\n|---|---|---|---|---|---|---|---|\n')
        for s in summary_rows:
            f.write('| %s | %d | %s | %s | %d | %d | %d / %d | %d |\n' % (
                s['project'], s['sessions'], s['first'], s['last'], s['prompts'], s['zero'], s['subagent_files'], s['unlinked'], s['parts']))
        f.write('\nTotals: sessions %d, prompts %d, zero-prompt sessions %d\n\n' % (
            sum(s['sessions'] for s in summary_rows), sum(s['prompts'] for s in summary_rows), sum(s['zero'] for s in summary_rows)))
        f.write('Excluded harness-injected user lines (all projects): %s\n\n' % json.dumps(
            dict(sum((collections.Counter(s['excluded']) for s in summary_rows), collections.Counter()))))
        f.write('Long project names shortened for file names:\n\n')
        for k, v in mapping.items():
            if k != v:
                f.write('- `%s` -> `%s`\n' % (k, v))
        f.write('\n')
        labels = [('slash', 'Slash commands'), ('skills', 'Skill invocations'), ('subagent_types', 'Subagent types (Agent/Task calls)'),
                  ('mcp', 'MCP tools'), ('sf', '`sf`/`sfdx` subcommands'), ('shell', 'Other shell commands'), ('write_ext', 'Written file extensions (Write/Edit)')]
        for proj in projects:
            agg = sumtables[proj]
            f.write('## %s\n\n' % proj)
            tables = dict(agg)
            sfd = {k: v for k, v in agg['shell'].items() if k.split(' ')[0] in ('sf', 'sfdx')}
            tables['sf'] = sfd
            tables['shell'] = {k: v for k, v in agg['shell'].items() if k not in sfd}
            for key, label in labels:
                d = tables[key]
                if not d:
                    continue
                f.write('**%s**\n\n| item | calls | sess |\n|---|---|---|\n' % label)
                for name, (n, s) in sorted(d.items(), key=lambda kv: (-kv[1][0], kv[0]))[:25]:
                    f.write('| %s | %d | %d |\n' % (name.replace('|', '\\|'), n, s))
                f.write('\n')

    with open(os.path.join(out, 'run-stats.json'), 'w', encoding='utf-8') as f:
        json.dump({'projects': summary_rows}, f, indent=1)
    for s in summary_rows:
        print('%s: %d sessions, %d prompts' % (s['project'], s['sessions'], s['prompts']))
    print('total: %d projects, %d sessions, %d prompts' % (
        len(summary_rows), sum(s['sessions'] for s in summary_rows), sum(s['prompts'] for s in summary_rows)))
    return 0


